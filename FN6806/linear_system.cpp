// if sol is empty, then prints message to the
// screen that there is no unique solution

// Generated by GPT
double sarrus_determinant(const std::vector<double> &mat)
{
    // Ensure the input is of size 9 (3x3 matrix)
    if (mat.size() != 9)
    {
        throw std::logic_error("Matrix must be 3x3 (9 elements).");
    }

    // Extract elements of the matrix
    double a = mat[0], b = mat[1], c = mat[2];
    double d = mat[3], e = mat[4], f = mat[5];
    double g = mat[6], h = mat[7], i = mat[8];

    return a * e * i + b * f * g + c * d * h - c * e * g - b * d * i - a * f * h;
    ;
}