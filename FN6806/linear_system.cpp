#include <cmath>
#include <iostream>
#include "linear_system.hpp"

LinearSystem::LinearSystem(std::vector<double> A, std::vector<double> b) : A(A), b(b) {} // Initializes A to A1 and b to b1

void LinearSystem::solve() const
{
    double det_A{sarrus_determinant(A)};
    if (std::abs(det_A) > 1e-10)
    {
        for (int col = 0; col < 3; ++col)
        {
            std::vector<double> A_replaced = A;
            for (int row = 0; row < 3; ++row)
            {
                A_replaced[row * 3 + col] = b[row];
            }
            sol.push_back(sarrus_determinant(A_replaced) / det_A);
        }
    }
}
// Sets sol to solution of Ax=b if abs(det(A))>1e/-10
// and sets sol to empty vector otherwise

void LinearSystem::print() const
{
    if (sol.size())
    {
        std::cout << "x = (" << sol[0] << ", " << sol[1] << ", " << sol[2] << ")`\n";
    }
    else
    {
        std::cout << "There is no unique solution!\n";
    }
}
