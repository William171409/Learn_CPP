void testShapeCollection()
{
    cout << "Testing ShapeCollection..." << endl;

    unique_ptr<Shape> rect = make_unique<Rectangle>(Coord(1.0, 1.0), 2.0, 3.0);
    unique_ptr<Shape> circ = make_unique<Circle>(Coord(2.0, 2.0), 1.0);

    ShapeCollection collection(make_unique<Rectangle>(Coord(0, 0), 1.0, 1.0));
    collection.add(std::move(rect)).add(std::move(circ));

    assert(collection.size() == 3);

    cout << collection << endl;

    collection.move(Coord(1.0, 1.0));
    cout << "After moving:" << endl;
    cout << collection << endl;

    collection.remove(1);
    assert(collection.size() == 2);

    cout << "ShapeCollection tests passed!" << endl;
}


