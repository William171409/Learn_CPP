// Alert: use std::move explicitly to avoid misuse of move method!!!
ShapeCollection &ShapeCollection::add(unique_ptr<Shape> S)
{
    elements.emplace_back(std::move(S));  
    return *this; 
}

ShapeCollection &ShapeCollection::remove(size_t i)
{
    if (i >= elements.size())
    {
        throw out_of_range("Index out of range for removal.");
    }
    elements.erase(elements.begin() + i);  
    return *this;
}

ShapeCollection &ShapeCollection::move(const Coord &offset)
{
    for (auto &shape : elements)
    {
        shape->move(offset);
    }
    return *this;
}

