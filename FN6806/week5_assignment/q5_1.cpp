#include <iostream>

// Transfers rate curve data into separate date and rate vectors.
void transfer_ratecurve(std::vector<int> &dates, std::vector<double> &rates,
                        const RateCurve &rc)
{
    if (dates.size() != rc.size() || rates.size() != rc.size()) {
        std::cerr << "Error: Vectors not resized properly!" << std::endl;
        return;
    }

    for (auto i = 0; i < rc.size(); ++i)
    {
        auto [d, r] = rc[i];
        dates[i] = d;
        rates[i] = r;
    }
}

double YieldCurve::interpolate(const std::vector<int> &dates,
                               const std::vector<double> &rates, const int date)
{
    if (dates.empty() || rates.empty())
    {
        std::cerr << "Error: Dates or rates vector is empty!" << std::endl;
        return std::numeric_limits<double>::quiet_NaN();
    }

    // Handle edge cases where date is outside the range of the provided curve
    if (date <= dates.front())
    {
        return rates.front();
    }
    if (date >= dates.back())
    {
        return rates.back();
    }

    // Perform linear interpolation for date within the range
    for (size_t i = 0; i < dates.size() - 1; ++i)
    {
        if (date >= dates[i] && date <= dates[i + 1])
        {
            double d1 = dates[i];
            double d2 = dates[i + 1];
            double r1 = rates[i];
            double r2 = rates[i + 1];
            return r1 + (r2 - r1) * (date - d1) / (d2 - d1);
        }
    }

    // Return NaN if input is incorrect and date does not fit logically.
    return std::numeric_limits<double>::quiet_NaN();
}

auto FixRatedBond::get_df(const int end, int today)
{
    std::vector<int> dates(IC.size());
    std::vector<double> rates(IC.size());

    // Transfer rate curve data from associated YieldCurve instance
    transfer_ratecurve(dates, rates, IC);

    double rate = y_curve->interpolate(dates, rates, end);
    double df = std::exp(-(end - today) / 365.0 * rate / 100.0);
    return df;
}

// Get payment date and corresponding discount factor
std::tuple<int, double> FixRatedBond::calculate_date_df(int today, int i, int frequency)
{
    int payment_date = today + (i + 1) * 365 / frequency;
    double df = get_df(payment_date, today);
    return std::make_tuple(payment_date, df);
}

