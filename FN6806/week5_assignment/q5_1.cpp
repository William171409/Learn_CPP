int FixRatedBond::getCouponFrequencyValue(const std::string &input)
{
    int k;
    if (input == "A")
    {
        k = 1;
    }
    else if (input == "S")
    {
        k = 2;
    }
    else if (input == "Q")
    {
        k = 4;
    }
    else
    {
        std::cerr << "Invalid input!" << std::endl;
        k = -1; // or handle error as needed
    }
    return k;
}

// Calculate bond price using zero-coupon discounting
double FixRatedBond::bond_price_zero() {
    // Get coupon payment frequency (e.g., Annual, Semi-Annual, Quarterly)
    int frequency = getCouponFrequencyValue(payment_schedule);
    if (frequency <= 0) {
        std::cerr << "Invalid coupon frequency value." << std::endl;
        return -1.0; // Indicate error
    }

    // Calculate the number of coupon payments
    int num_payments = static_cast<int>(frequency * maturity);

    // Prepare storage for payment dates and discount factors
    std::vector<std::tuple<int, double>> date_bond_price_vector(num_payments);

    // Populate date-bond price vector for all payment dates except the last one
    for (int i = 0; i < num_payments - 1; ++i) {
        date_bond_price_vector[i] = calculate_date_df(today, i, frequency);
    }

    // Handle final payment
    int final_payment_date = today + static_cast<int>(maturity * 365);
    double final_df = get_df(final_payment_date, today);
    date_bond_price_vector.back() = std::make_tuple(final_payment_date, final_df);

    // Compute total bond price
    double total_price = 0.0;
    for (const auto &tp : date_bond_price_vector) {
        int date = std::get<0>(tp);
        double df = std::get<1>(tp);
        double payment = (date == final_payment_date)
                             ? face_value * (1 + coupon_rate / frequency)
                             : (face_value * coupon_rate / frequency);
        total_price += payment * df;
    }

    return total_price;
}

